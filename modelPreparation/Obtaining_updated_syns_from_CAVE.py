# -------------------------------
# Helper to unpack _position columns to x/y/z
# Positions are 3-vectors in nanometers; we'll create *_x/y/z columns.
# -------------------------------
def unpack_position_to_xyz(df: pd.DataFrame, source_col: str, out_prefix: str):
    """
    df[source_col] contains [x, y, z] (list/tuple/array) or dict with keys x,y,z.
    Creates df[f"{out_prefix}_x"], _y, _z.
    """
    def get_xyz(p):
        if p is None:
            return (pd.NA, pd.NA, pd.NA)
        # dict-like with keys 'x','y','z'
        if isinstance(p, dict):
            return (p.get('x', pd.NA), p.get('y', pd.NA), p.get('z', pd.NA))
        # list/tuple/np.ndarray-like
        try:
            return (p[0], p[1], p[2])
        except Exception:
            return (pd.NA, pd.NA, pd.NA)

    xyz = df[source_col].apply(get_xyz).apply(pd.Series)
    xyz.columns = [f"{out_prefix}_x", f"{out_prefix}_y", f"{out_prefix}_z"]
    return pd.concat([df, xyz], axis=1)

